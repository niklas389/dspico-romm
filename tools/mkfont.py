# Rasterizes DejaVu Sans into 4-bit anti-aliased bitmap fonts for the UI
# (source/font_data.c). Glyphs: Latin-1, Latin Extended-A and a few symbols.
# The DejaVu license is in source/third_party/dejavu/LICENSE.
#
# Usage: tools/mkfont.py [fontdir] > source/font_data.c

import sys
from PIL import Image, ImageDraw, ImageFont

FONTDIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu"

# name, file, pixel size
FONTS = [
    ("font_small", "DejaVuSans.ttf", 10),
    ("font_bold", "DejaVuSans-Bold.ttf", 10),
    ("font_title", "DejaVuSans-Bold.ttf", 13),
]

CODEPOINTS = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) +
              [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026,
               0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x25B2, 0x25B6, 0x25BC,
               0x25C0, 0x25CF, 0x2713, 0x2717, 0xFFFD])


def raster(fontfile, size):
    font = ImageFont.truetype(f"{FONTDIR}/{fontfile}", size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    pad = size
    for cp in CODEPOINTS:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        canvas = Image.new("L", (size * 3 + 2 * pad, ascent + descent + 2 * pad), 0)
        ImageDraw.Draw(canvas).text((pad, pad + ascent), ch, font=font, fill=255,
                                    anchor="ls")
        bbox = canvas.getbbox()
        if bbox is None:
            glyphs.append((cp, 0, 0, 0, 0, adv, len(data)))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        off = len(data)
        for y in range(y0, y1):
            row = [canvas.getpixel((x, y)) >> 4 for x in range(x0, x1)]
            if len(row) % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                data.append(row[i] | (row[i + 1] << 4))
        glyphs.append((cp, w, h, x0 - pad, y0 - pad, adv, off))
    return glyphs, data, ascent, descent


def main():
    out = []
    out.append("// SPDX-License-Identifier: MIT")
    out.append("// Generated by tools/mkfont.py from DejaVu Sans (Bitstream Vera")
    out.append("// license, see source/third_party/dejavu/LICENSE). Do not edit.")
    out.append("#include \"font.h\"\n")
    for name, f, size in FONTS:
        glyphs, data, ascent, descent = raster(f, size)
        out.append(f"static const font_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for cp, w, h, xo, yo, adv, off in glyphs:
            out.append(f"    {{ 0x{cp:04X}, {w}, {h}, {xo}, {yo}, {adv}, {off} }},")
        out.append("};\n")
        out.append(f"static const unsigned char {name}_bits[{max(1, len(data))}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
        out.append("};\n")
        out.append(f"const font_t {name} = {{ {name}_glyphs, {len(glyphs)}, {name}_bits, "
                   f"{ascent + descent}, {ascent} }};\n")
    print("\n".join(out))


main()
